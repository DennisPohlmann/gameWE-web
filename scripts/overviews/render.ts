// A map's radar picture and calibration as files.
import { readFileSync, writeFileSync } from "node:fs";
import type { Bsp, Poly } from "./bsp.ts";
import { Canvas, REF, draw, encodePng, floorFaces, low, navPolys, pyFloat, pyRound, readNav, synthNav } from "./draw.ts";

/** navPath "-": the walkable floor is worked out from the spawn points.
 *  Returns the calibration as Python's print would show it. */
export function render(bsp: Bsp, navPath: string, outPng: string, outJson: string, split: number | null = null): string {
  const floors = floorFaces(bsp);
  let navpolys: Poly[] | null = null;
  if (navPath !== "-") {
    try {
      navpolys = navPolys(readNav(readFileSync(navPath))[1]);
    } catch (e) {
      // another game's nav version: walk it instead
      console.error(`nav unreadable (${(e as Error).message}), walking the map`);
    }
  }
  navpolys ??= synthNav(bsp, floors);
  let [minx, maxx, miny, maxy] = [Infinity, -Infinity, Infinity, -Infinity];
  for (const p of navpolys.length ? navpolys : floors) {
    for (let i = 0; i < p.length; i += 3) {
      minx = Math.min(minx, p[i]);
      maxx = Math.max(maxx, p[i]);
      miny = Math.min(miny, p[i + 1]);
      maxy = Math.max(maxy, p[i + 1]);
    }
  }
  if (minx > maxx) throw new Error("no floors in the map");
  const side = Math.max(maxx - minx, maxy - miny) * 1.08;
  const canvas = new Canvas((minx + maxx) / 2 - side / 2, (miny + maxy) / 2 + side / 2, side);

  writeFileSync(outPng, encodePng(draw(canvas, floors, navpolys)));
  const cal: [string, string][] = [
    ["pos_x", pyFloat(pyRound(canvas.minx, 2))],
    ["pos_y", pyFloat(pyRound(canvas.maxy, 2))],
    ["scale", pyFloat(pyRound(side / REF, 5))],
  ];
  if (split !== null) {
    const isLow = low(split);
    const lower = new Canvas(canvas.minx, canvas.maxy, side);
    writeFileSync(outPng.replaceAll(".png", "_lower.png"), encodePng(draw(lower, floors.filter(isLow), navpolys.filter(isLow))));
    cal.push(["lower_split", pyFloat(split)]);
  }
  const source = "generated by gameWE from the map file";
  writeFileSync(outJson, `{${[...cal.map(([k, v]) => `"${k}": ${v}`), `"source": "${source}"`].join(", ")}}\n`);
  return `{${[...cal.map(([k, v]) => `'${k}': ${v}`), `'source': '${source}'`].join(", ")}}`;
}
