// Draws all flags of public/flags/*.svg into one sprite,
// public/flags/sprite.png, and writes the codes and the layout to
// src/lib/flag-sprite.ts. The pages show every flag out of this one picture
// (background-position), so a list with a hundred players costs one request
// instead of one per country (the SVGs are up to 180 KB each).
//
//   npm run flags      (after changing public/flags)
//
// The sprite and the module are committed; the script needs the
// devDependency `sharp`. Cells are 48 x 36 (3x of the 16 x 12 px flags),
// 16 per row, in the order of the codes.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "public", "flags");
const W = 48;
const H = 36;
const COLS = 16;

const codes = (await readdir(dir))
  .filter((f) => f.endsWith(".svg"))
  .map((f) => f.slice(0, -4))
  .sort();
const rows = Math.ceil(codes.length / COLS);

const cells = await Promise.all(
  codes.map(async (code, i) => ({
    input: await sharp(await readFile(path.join(dir, `${code}.svg`)), { density: 72 * 3 })
      .resize(W, H, { fit: "fill" })
      .png()
      .toBuffer(),
    left: (i % COLS) * W,
    top: Math.floor(i / COLS) * H,
  })),
);
const png = await sharp({ create: { width: COLS * W, height: rows * H, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(cells)
  .png({ compressionLevel: 9, palette: true, quality: 90 })
  .toBuffer();
await writeFile(path.join(dir, "sprite.png"), png);
const hash = createHash("sha256").update(png).digest("hex").slice(0, 8);

const chunk = [];
for (let i = 0; i < codes.length; i += 26) chunk.push(codes.slice(i, i + 26).join(" "));
await writeFile(
  path.join(root, "src", "lib", "flag-sprite.ts"),
  `// Generated by scripts/flags-sprite.mjs (npm run flags) from public/flags:
// do not edit. The flags in the order of the sprite, 16 per row; \`v\` is the
// picture's hash, for the cache.
export const FLAG_SPRITE = {
  v: "${hash}",
  cols: ${COLS},
  rows: ${rows},
  codes: \`${chunk.join("\n")}\`.split(/\\s+/),
};
`,
);
console.log(`flags: ${codes.length} flags, ${COLS} x ${rows} cells, ${(png.length / 1024).toFixed(0)} KB, v=${hash}`);
